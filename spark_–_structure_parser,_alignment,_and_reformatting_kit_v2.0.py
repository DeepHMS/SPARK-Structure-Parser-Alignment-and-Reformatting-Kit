"""## **Remove H2O (Water) from pdb**"""

def remove_water_from_pdb(input_filepath, output_filepath):
    """Removes all HOH (water) molecules from a PDB file."""

    with open(input_filepath, 'r') as infile, open(output_filepath, 'w') as outfile:
        count = 0
        for line in infile:
            # If the line represents an atom and belongs to HOH, skip it
            if line.startswith("HETATM") and "HOH" in line:
                count += 1
                continue

            # Otherwise, keep the line
            outfile.write(line)

    print(f"✅ Removed {count} water atoms.")
    print(f"✅ Saved clean protein to: {output_filepath}")

