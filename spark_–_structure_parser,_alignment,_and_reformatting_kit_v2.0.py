def universal_chain_extractor(input_filepath, output_filepath, target_chain='A'):
    """
    Extracts any specified chain from a PDB file safely in a single pass.
    Handles standard letters, lowercase, numbers, or blank chains.
    """
    # If the user wants a blank chain, search for a space character
    if target_chain == '' or target_chain is None:
        target_chain = ' '

    atom_count = 0

    with open(input_filepath, 'r') as infile, open(output_filepath, 'w') as outfile:
        for line in infile:
            # 1. Copy standard file headers as we encounter them
            if line.startswith(("HEADER", "TITLE", "COMPND", "REMARK")):
                outfile.write(line)
                continue  # Move to the next line immediately

            # 2. Check for structural and coordinate lines
            if line.startswith(("ATOM", "HETATM", "ANISOU", "TER")):
                # Ensure the line is long enough to contain the chain ID (column 22 / index 21)
                if len(line) > 21:
                    current_chain = line[21]
                    if current_chain == target_chain:
                        outfile.write(line)
                        if line.startswith(("ATOM", "HETATM")):
                            atom_count += 1
                # Handle edge-case TER lines that might be truncated short but belong to our chain
                elif line.startswith("TER") and atom_count > 0:
                    outfile.write(line)

        # Always write a clean END tag at the very bottom of the new PDB file
        outfile.write("END\n")

    if atom_count == 0:
        print(f"⚠️ Warning: No atoms found for Chain '{target_chain}'. Check if the file uses a different ID or a blank space.")
    else:
        print(f"✅ Successfully extracted Chain '{target_chain}' ({atom_count} atoms) -> {output_filepath}")

