import json
from Bio.PDB import MMCIFParser, PDBIO

def convert_specific_boltz_json(json_filepath, output_pdb_filepath):
    print(f"Parsing {json_filepath}...")

    # 1. Load the JSON data
    with open(json_filepath, "r") as f:
        data = json.load(f)

    # 2. Extract the mmCIF structure block
    structure_text = data["structures"][0]["structure"]

    # 3. Write it out as a temporary .cif file
    temp_cif = "temp_output.cif"
    with open(temp_cif, "w") as f:
        f.write(structure_text)

    print("Structure extracted. Translating mmCIF format to PDB...")

    # 4. Read it as mmCIF and save as clean PDB
    try:
        parser = MMCIFParser(QUIET=True)
        structure = parser.get_structure("protein_structure", temp_cif)

        io = PDBIO()
        io.set_structure(structure)
        io.save(output_pdb_filepath)
        print(f"✅ Success! Your file is ready at: {output_pdb_filepath}")

    except Exception as e:
        print(f"❌ Conversion failed: {e}")

    finally:
        # Clean up the temporary .cif file automatically
        import os
        if os.path.exists(temp_cif):
            os.remove(temp_cif)

# Execute the conversion
convert_specific_boltz_json("Q9BV20.json", "Q9BV20.pdb")

