import json

def extract_pdb_from_json(json_filepath, output_pdb_filepath):
    """Extracts the PDB structure from the Boltz JSON file and saves it."""

    print(f"Reading JSON file: {json_filepath}...")

    # 1. Open and read the JSON envelope
    try:
        with open(json_filepath, "r") as f:
            data = json.load(f)
    except Exception as e:
        print(f"❌ Failed to read JSON: {e}")
        return

    # 2. Extract the structure string
    structure_string = None

    # Check for the key used in your specific file
    if "structures_in_ranked_order" in data:
        structure_string = data["structures_in_ranked_order"][0]["structure"]
    # Fallback to the standard key just in case
    elif "structures" in data:
        structure_string = data["structures"][0]["structure"]
    else:
        print("❌ Could not find the structure data inside the JSON.")
        return

    # 3. Save it directly as a PDB file!
    # (The string is already in PDB format, so no Biopython conversion is needed)
    try:
        with open(output_pdb_filepath, "w") as f:
            f.write(structure_string)
        print(f"✅ Success! Saved as: {output_pdb_filepath}")
    except Exception as e:
        print(f"❌ Failed to save PDB file: {e}")

