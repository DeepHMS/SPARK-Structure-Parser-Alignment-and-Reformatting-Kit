import py3Dmol
import glob
import os
import math

def create_linked_viewer_dark(directory="."):
    # 1. Find and count all .pdb files
    pdb_files = sorted(glob.glob(os.path.join(directory, "*.pdb")))
    num_files = len(pdb_files)

    if num_files == 0:
        print("❌ No .pdb files found in the current directory.")
        return

    print(f"✅ Found {num_files} PDB files. Building dark-mode viewer...")

    cols = math.ceil(math.sqrt(num_files))
    rows = math.ceil(num_files / cols)

    # 2. Create the grid
    view = py3Dmol.view(viewergrid=(rows, cols), linked=True, width=1000, height=400 * rows)

    # 🌟 NEW: Set the global background color to black
    view.setBackgroundColor('black')

    print("\n--- Grid Layout Guide ---")

    for i, filepath in enumerate(pdb_files):
        filename = os.path.basename(filepath)
        row = i // cols
        col = i % cols

        print(f"Window (Row {row}, Col {col}): {filename}")

        with open(filepath, 'r') as f:
            pdb_data = f.read()

        view.addModel(pdb_data, 'pdb', viewer=(row, col))
        view.setStyle({'cartoon': {'color': 'spectrum'}}, viewer=(row, col))
        view.zoomTo(viewer=(row, col))

    print("-" * 25)
    view.show()

