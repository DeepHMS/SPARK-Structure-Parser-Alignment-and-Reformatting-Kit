import os
import pandas as pd
import glob
import numpy as np
from Bio.PDB import PDBParser, Superimposer

def calculate_rg(atoms):
    """Calculates the Radius of Gyration from a list of Biopython atoms."""
    coords = np.array([atom.get_coord() for atom in atoms])
    center_of_mass = coords.mean(axis=0)
    rg = np.sqrt(np.sum((coords - center_of_mass)**2) / len(coords))
    return round(rg, 2)

def generate_ultimate_table(directory=".", reference_pdb="Q9BV20.pdb"):
    pdb_files = glob.glob(os.path.join(directory, "*.pdb"))
    parser = PDBParser(QUIET=True)

    # Load reference structure for RMSD calculation
    try:
        ref_structure = parser.get_structure("ref", os.path.join(directory, reference_pdb))
        ref_ca = [atom for atom in ref_structure[0]['A'].get_atoms() if atom.get_name() == 'CA']
    except:
        ref_ca = None
        print(f"⚠️ Could not load reference {reference_pdb} for RMSD calculations.")

    results = []

    for filepath in pdb_files:
        filename = os.path.basename(filepath)

        # --- 1. Basic Metrics (Text Parsing) ---
        chains = set()
        residues = set()
        atom_count = 0
        hetatm_count = 0
        b_factors = []

        with open(filepath, 'r') as f:
            for line in f:
                if line.startswith("ATOM"):
                    atom_count += 1
                    if len(line) > 21:
                        chains.add(line[21])
                    if len(line) > 26:
                        res_num = line[22:26].strip()
                        chain_id = line[21]
                        residues.add(f"{chain_id}_{res_num}")
                    if len(line) > 66:
                        try:
                            b_factors.append(float(line[60:66].strip()))
                        except ValueError:
                            pass
                elif line.startswith("HETATM"):
                    hetatm_count += 1

        avg_bfactor = sum(b_factors) / len(b_factors) if b_factors else 0

        # --- 2. Advanced Metrics (Biopython Parsing) ---
        rg = "N/A"
        rmsd_val = "N/A"
        structure = parser.get_structure(filename, filepath)

        try:
            model = structure[0]
            chain_A = model['A']

            # Calculate Radius of Gyration (Heavy atoms only)
            heavy_atoms = [atom for atom in chain_A.get_atoms() if atom.element != 'H']
            rg = calculate_rg(heavy_atoms)

            # Calculate RMSD
            if ref_ca and filename != reference_pdb:
                target_ca = [atom for atom in chain_A.get_atoms() if atom.get_name() == 'CA']
                ref_res_ids = [atom.get_parent().get_id()[1] for atom in ref_ca]
                target_ca_matched = [atom for atom in target_ca if atom.get_parent().get_id()[1] in ref_res_ids]

                if len(ref_ca) == len(target_ca_matched):
                    superimposer = Superimposer()
                    superimposer.set_atoms(ref_ca, target_ca_matched)
                    rmsd_val = round(superimposer.rms, 2)
                else:
                    rmsd_val = "Mismatch"
        except KeyError:
            pass # Skip advanced math if Chain A is missing

        # --- 3. Combine into final row ---
        results.append({
            "File / Model": filename,
            "Chains": ", ".join(sorted(list(chains))) if chains else "None",
            "Total Residues": len(residues),
            "Total Atoms": atom_count,
            "HETATM": hetatm_count,
            "Avg Score/B-Factor": round(avg_bfactor, 2),
            "Radius of Gyration (Å)": rg,
            "RMSD to PDB (Å)": rmsd_val if filename != reference_pdb else "0.0 (Reference)"
        })

    df = pd.DataFrame(results).sort_values(by="File / Model").reset_index(drop=True)
    return df

# Run the master analysis
