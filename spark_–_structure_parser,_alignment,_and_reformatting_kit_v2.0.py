def get_multiline_input(prompt_text):
    """Reads multi-line input from the user until an empty line is entered."""
    print(f"\n{prompt_text}")
    print("When you are done pasting, press ENTER on an empty line to finish:")
    lines = []
    while True:
        line = input()
        if not line.strip():
            break
        lines.append(line.strip())
    return "\n".join(lines)

def parse_user_sequence(raw_input):
    """Removes all spaces, tabs, and line breaks from the pasted text."""
    return "".join(raw_input.split())

def extract_pdb_record(pdb_file_path):
    """
    Extracts chains from a PDB file. 
    Detects multiple chains and warns the user interactively.
    """
    try:
        with open(pdb_file_path, 'r') as pdb_file:
            records = list(SeqIO.parse(pdb_file, 'pdb-atom'))
            
        if not records:
            print("  [!] No sequences found in this PDB.")
            return None
            
        # --- Multi-Chain Detection & Warning ---
        if len(records) > 1:
            chain_ids = [rec.id for rec in records]
            print(f"\n  ⚠️ WARNING: Multiple chains detected in this PDB: {chain_ids}")
            print("  This script aligns against the FIRST chain by default.")
            print("  If you need a specific chain, please use SPARK to convert your")
            print("  multi-chain PDB into a single chain and re-upload.")
            
            ans = input("\n  Do you want to proceed using ONLY the first chain? (y/n): ").strip().lower()
            if ans != 'y':
                print("  -> Skipping this PDB file. Please process it in SPARK first.")
                return None
                
        return records[0] # Return the first SeqRecord
    except Exception as e:
        print(f"  [!] Error reading {pdb_file_path}: {e}")
        return None

def print_colored_alignment(alignment_str):
    """Parses a Biopython pairwise alignment string and adds Green/Red ANSI colors."""
    GREEN = '\033[92m'
    RED = '\033[91m'
    RESET = '\033[0m'
    
    lines = alignment_str.strip().split('\n')
    i = 0
    while i < len(lines):
        target = lines[i]
        if not target.startswith("target"):
            print(target)
            i += 1
            continue
            
        match = lines[i+1]
        query = lines[i+2]
        
        c_target, c_match, c_query = "", "", ""
        
        # Find where the sequence starts to avoid coloring the header names/numbers
        seq_start_idx = 0
        for idx, char in enumerate(match):
            if char in ('|', '.'):
                seq_start_idx = idx
                break
        if seq_start_idx == 0: seq_start_idx = 15 
            
        # Walk back to the space so we don't chop a coordinate number in half
        while seq_start_idx > 0 and target[seq_start_idx-1] != ' ':
            seq_start_idx -= 1
            
        for idx, (t, m, q) in enumerate(zip(target, match, query)):
            # Skip coloring the labels (e.g., "target    0")
            if idx < seq_start_idx:
                c_target += t; c_match += m; c_query += q
                continue
                
            # Exact Match -> Green
            if m == '|':
                c_target += f"{GREEN}{t}{RESET}"
                c_match  += f"{GREEN}{m}{RESET}"
                c_query  += f"{GREEN}{q}{RESET}"
            # Mismatch or Gap -> Red
            elif m == '.' or (m == ' ' and (t == '-' or q == '-')) or (m == ' ' and t.isalpha() and q.isalpha()):
                c_target += f"{RED}{t}{RESET}"
                c_match  += f"{RED}{m}{RESET}"
                c_query  += f"{RED}{q}{RESET}"
            else:
                c_target += t; c_match += m; c_query += q
        
        print(c_target)
        print(c_match)
        print(c_query)
        print("")
        i += 4

