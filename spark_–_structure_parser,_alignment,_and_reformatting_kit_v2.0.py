"""## **Remove All Hydrogen**"""

def remove_hydrogens(input_filepath, output_filepath):
    """Removes all Hydrogen (H) atoms from a PDB file."""

    with open(input_filepath, 'r') as infile, open(output_filepath, 'w') as outfile:
        atom_count = 0
        hydrogen_count = 0

        for line in infile:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                # In PDB format, the element symbol is usually in columns 77-78
                # But a safer way is to check the atom name starting character
                atom_name = line[12:16].strip()
                if atom_name.startswith('H') or (len(line) > 77 and line[76:78].strip() == 'H'):
                    hydrogen_count += 1
                    continue # Skip this line
                else:
                    atom_count += 1

            outfile.write(line)

    print(f"✅ Removed {hydrogen_count} Hydrogen atoms.")
    print(f"✅ Remaining Heavy Atoms: {atom_count}")
    print(f"✅ Saved to: {output_filepath}")

